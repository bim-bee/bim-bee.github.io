#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const root = path.resolve(__dirname, "..");
const sourcePath = path.join(root, "TERMS OF USE.md");
const outputPath = path.join(__dirname, "terms-content.js");
const markdown = fs.readFileSync(sourcePath, "utf8");
const hash = crypto.createHash("sha256").update(markdown).digest("hex");
const output = `/* GENERATED from TERMS OF USE.md. Do not edit this file directly.\n   Source SHA-256: ${hash} */\n(function exposeNcNestingTermsDocument() {\n  \"use strict\";\n  window.NcNestingTermsDocument = Object.freeze({\n    markdown: ${JSON.stringify(markdown)}\n  });\n})();\n`;
fs.writeFileSync(outputPath, output, "utf8");
console.log(`Updated ${path.relative(root, outputPath)} from TERMS OF USE.md`);
